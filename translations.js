// Función para detectar el idioma del navegador
function detectBrowserLanguage() {
    const browserLang = navigator.language || navigator.userLanguage;
    return browserLang.toLowerCase().startsWith('es') ? 'es' : 'en';
}

// Función para obtener el idioma guardado o detectado
function getCurrentLanguage() {
    const savedLang = localStorage.getItem('toccaLanguage');
    return savedLang || detectBrowserLanguage();
}

// Función para cambiar el idioma
function setLanguage(lang) {
    localStorage.setItem('toccaLanguage', lang);
    applyTranslations(lang);
    updateLanguageButton(lang);
    updateHtmlLang(lang);
}

// Función para aplicar las traducciones
function applyTranslations(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Si el elemento tiene data-i18n-html, usar innerHTML, sino textContent
            if (element.hasAttribute('data-i18n-html')) {
                element.innerHTML = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });

    // Actualizar meta tags
    updateMetaTags(lang);
}

// Función para actualizar los meta tags
function updateMetaTags(lang) {
    const titleElement = document.querySelector('title');
    const descriptionMeta = document.querySelector('meta[name="description"]');
    const ogTitle = document.querySelector('meta[property="og:title"]');
    const ogDescription = document.querySelector('meta[property="og:description"]');
    const twitterTitle = document.querySelector('meta[property="twitter:title"]');
    const twitterDescription = document.querySelector('meta[property="twitter:description"]');

    if (titleElement && translations[lang]['meta.title']) {
        titleElement.textContent = translations[lang]['meta.title'];
    }
    if (descriptionMeta && translations[lang]['meta.description']) {
        descriptionMeta.setAttribute('content', translations[lang]['meta.description']);
    }
    if (ogTitle && translations[lang]['meta.title']) {
        ogTitle.setAttribute('content', translations[lang]['meta.title']);
    }
    if (ogDescription && translations[lang]['meta.description']) {
        ogDescription.setAttribute('content', translations[lang]['meta.description']);
    }
    if (twitterTitle && translations[lang]['meta.title']) {
        twitterTitle.setAttribute('content', translations[lang]['meta.title']);
    }
    if (twitterDescription && translations[lang]['meta.description']) {
        twitterDescription.setAttribute('content', translations[lang]['meta.description']);
    }
}

// Función para actualizar el atributo lang del HTML
function updateHtmlLang(lang) {
    document.documentElement.setAttribute('lang', lang);
}

// Función para actualizar el botón de idioma
function updateLanguageButton(lang) {
    const langButton = document.getElementById('language-toggle');
    if (langButton) {
        const flag = lang === 'es' ? '🇺🇸' : '🇪🇸';
        const text = lang === 'es' ? 'EN' : 'ES';
        langButton.innerHTML = `${flag} <span>${text}</span>`;
        langButton.setAttribute('aria-label', lang === 'es' ? 'Switch to English' : 'Cambiar a Español');
    }
}

// Función para alternar idioma
function toggleLanguage() {
    const currentLang = getCurrentLanguage();
    const newLang = currentLang === 'en' ? 'es' : 'en';
    setLanguage(newLang);
}

// Inicializar el sistema de traducción cuando el DOM esté listo
document.addEventListener('DOMContentLoaded', function() {
    const currentLang = getCurrentLanguage();
    setLanguage(currentLang);

    // Agregar event listener al botón de idioma
    const langButton = document.getElementById('language-toggle');
    if (langButton) {
        langButton.addEventListener('click', toggleLanguage);
    }
});
